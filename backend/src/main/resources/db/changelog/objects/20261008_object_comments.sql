UPDATE object_comments SET edited_at=updated_at WHERE version>0 OR updated_at<>created_at;;
WITH ordered AS (SELECT id,row_number() OVER(ORDER BY created_at,id) position FROM object_comments)
UPDATE object_comments c SET sequence=ordered.position FROM ordered WHERE c.id=ordered.id;;
SELECT setval(pg_get_serial_sequence('object_comments','sequence'),
    COALESCE((SELECT max(sequence) FROM object_comments),1),EXISTS(SELECT 1 FROM object_comments));;
CREATE UNIQUE INDEX ux_object_comments_sequence ON object_comments(sequence);;
CREATE INDEX ix_object_comments_page ON object_comments(object_id,sequence);;
CREATE FUNCTION maintain_object_comment() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.id,NEW.object_id,NEW.author_id,NEW.created_at,NEW.sequence) IS DISTINCT FROM
       (OLD.id,OLD.object_id,OLD.author_id,OLD.created_at,OLD.sequence)
    THEN RAISE EXCEPTION 'Comment identity is immutable' USING ERRCODE='23514'; END IF;
    IF NEW.body IS DISTINCT FROM OLD.body THEN
        NEW.version := OLD.version+1;
        NEW.edited_at := clock_timestamp();
        NEW.updated_at := NEW.edited_at;
    ELSE
        NEW.version := OLD.version;
        NEW.edited_at := OLD.edited_at;
        NEW.updated_at := OLD.updated_at;
    END IF;
    RETURN NEW;
END $$;;
CREATE TRIGGER object_comment_metadata BEFORE UPDATE ON object_comments FOR EACH ROW EXECUTE FUNCTION maintain_object_comment();;
