-- Restore approval events that predate the history API.
WITH requests AS (
    SELECT id,object_id,initiator_id,object_version,status,decided_by_id,created_at,updated_at,
           'STATUS_APPROVAL' AS kind,to_jsonb(r)-'created_at'-'updated_at' AS detail
    FROM status_approval_requests r
    UNION ALL
    SELECT id,object_id,initiator_id,object_version,status,decided_by_id,created_at,updated_at,
           'ENTRY_POINT_APPROVAL',to_jsonb(r)-'created_at'-'updated_at'
    FROM entry_point_approval_requests r
)
INSERT INTO object_history(object_id,author_id,actor_type,field_name,previous_value,new_value,object_version,created_at)
SELECT object_id,initiator_id,'USER',kind||'_REQUESTED',NULL,
       ((detail-'decided_by_id')||jsonb_build_object('status','PENDING'))::text,object_version,created_at
FROM requests r WHERE NOT EXISTS (SELECT 1 FROM object_history h
    WHERE h.object_id=r.object_id AND
        CASE WHEN h.field_name=r.kind||'_REQUESTED' THEN h.new_value::jsonb->>'id' END=r.id::text)
UNION ALL
SELECT object_id,decided_by_id,CASE WHEN decided_by_id IS NULL THEN 'SYSTEM' ELSE 'USER' END,
       kind||'_'||status,'PENDING',jsonb_build_object('requestId',id,'decision',status)::text,
       object_version,updated_at FROM requests r WHERE status<>'PENDING'
       AND NOT EXISTS (SELECT 1 FROM object_history h WHERE h.object_id=r.object_id
           AND CASE WHEN h.field_name=r.kind||'_'||r.status
               THEN h.new_value::jsonb->>'requestId' END=r.id::text);;

WITH ordered AS (SELECT id,row_number() OVER (ORDER BY created_at,id) AS position FROM object_history)
UPDATE object_history h SET sequence=ordered.position FROM ordered WHERE ordered.id=h.id;;
SELECT setval(pg_get_serial_sequence('object_history','sequence'),
              COALESCE((SELECT max(sequence) FROM object_history),1),
              EXISTS(SELECT 1 FROM object_history));;
CREATE UNIQUE INDEX ux_object_history_sequence ON object_history(sequence);;
CREATE INDEX ix_object_history_page ON object_history(object_id,sequence);;

CREATE FUNCTION record_object_approval_history() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE kind text; actor uuid; current_version bigint;
BEGIN
    kind := CASE WHEN TG_TABLE_NAME='status_approval_requests' THEN 'STATUS_APPROVAL' ELSE 'ENTRY_POINT_APPROVAL' END;
    IF TG_OP='UPDATE' AND NEW.status=OLD.status THEN RETURN NEW; END IF;
    SELECT version INTO current_version FROM objects WHERE id=NEW.object_id;
    actor := CASE WHEN TG_OP='INSERT' THEN NEW.initiator_id ELSE NEW.decided_by_id END;
    INSERT INTO object_history(object_id,author_id,actor_type,field_name,previous_value,new_value,object_version,created_at)
    VALUES (NEW.object_id,actor,CASE WHEN actor IS NULL THEN 'SYSTEM' ELSE 'USER' END,
        kind||CASE WHEN TG_OP='INSERT' THEN '_REQUESTED' ELSE '_'||NEW.status END,
        CASE WHEN TG_OP='INSERT' THEN NULL ELSE OLD.status END,
        CASE WHEN TG_OP='INSERT' THEN (to_jsonb(NEW)-'created_at'-'updated_at')::text
             ELSE jsonb_build_object('requestId',NEW.id,'decision',NEW.status)::text END,
        current_version,clock_timestamp());
    RETURN NEW;
END $$;;
CREATE TRIGGER status_approval_history AFTER INSERT OR UPDATE ON status_approval_requests
FOR EACH ROW EXECUTE FUNCTION record_object_approval_history();;
CREATE TRIGGER entry_point_approval_history AFTER INSERT OR UPDATE ON entry_point_approval_requests
FOR EACH ROW EXECUTE FUNCTION record_object_approval_history();;

CREATE TABLE IF NOT EXISTS object_deletion_audit (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    object_id uuid NOT NULL,
    actor_id uuid NOT NULL,
    event_type varchar(100) NOT NULL DEFAULT 'OBJECT_DELETED' CHECK (event_type='OBJECT_DELETED'),
    object_version bigint NOT NULL,
    snapshot jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp()
);;
CREATE INDEX IF NOT EXISTS ix_object_deletion_audit_object ON object_deletion_audit(object_id,created_at);;

CREATE FUNCTION archive_deleted_object() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE actor uuid;
BEGIN
    actor := NULLIF(current_setting('workflow.object_deletion_actor',true),'')::uuid;
    IF actor IS NULL OR NOT EXISTS (
        SELECT 1 FROM users u JOIN roles r ON r.id=u.role_id
        WHERE u.id=actor AND u.status='ACTIVE' AND r.code='SUPERADMIN'
    ) THEN RAISE EXCEPTION 'Physical object deletion requires an active administrator' USING ERRCODE='42501'; END IF;
    INSERT INTO object_deletion_audit(object_id,actor_id,object_version,snapshot)
    VALUES (OLD.id,actor,OLD.version,jsonb_build_object('object',to_jsonb(OLD),'contacts',
        COALESCE((SELECT jsonb_agg(to_jsonb(c)) FROM object_contacts oc JOIN contacts c ON c.id=oc.contact_id
                  WHERE oc.object_id=OLD.id),'[]'::jsonb)));
    RETURN OLD;
END $$;;
CREATE TRIGGER archive_object_before_delete BEFORE DELETE ON objects
FOR EACH ROW EXECUTE FUNCTION archive_deleted_object();;

