CREATE FUNCTION protect_object_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' AND NOT EXISTS (SELECT 1 FROM objects WHERE id=OLD.object_id)
        AND EXISTS (SELECT 1 FROM object_deletion_audit WHERE object_id=OLD.object_id)
    THEN RETURN OLD; END IF;
    RAISE EXCEPTION 'Object history is immutable' USING ERRCODE='42501';
END $$;;
CREATE TRIGGER immutable_object_history BEFORE UPDATE OR DELETE ON object_history
FOR EACH ROW EXECUTE FUNCTION protect_object_history();;
CREATE OR REPLACE FUNCTION protect_object_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Object audit is immutable' USING ERRCODE='42501'; END $$;;
CREATE TRIGGER immutable_object_history_truncate BEFORE TRUNCATE ON object_history
FOR EACH STATEMENT EXECUTE FUNCTION protect_object_audit();;
DROP TRIGGER IF EXISTS immutable_object_deletion_audit ON object_deletion_audit;;
CREATE TRIGGER immutable_object_deletion_audit BEFORE UPDATE OR DELETE ON object_deletion_audit
FOR EACH ROW EXECUTE FUNCTION protect_object_audit();;
DROP TRIGGER IF EXISTS immutable_object_deletion_audit_truncate ON object_deletion_audit;;
CREATE TRIGGER immutable_object_deletion_audit_truncate BEFORE TRUNCATE ON object_deletion_audit
FOR EACH STATEMENT EXECUTE FUNCTION protect_object_audit();;
